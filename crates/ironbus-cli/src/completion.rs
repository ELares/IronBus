//! Shell-completion generation and the `cheat` sheet (V2-M6, #598).
//!
//! Completion is generated from ONE declarative description of the command tree ([`COMMAND_TREE`]),
//! which is the single source of truth: the bash, zsh, and fish generators all walk the SAME table,
//! so a completion can never drift from a hand-maintained per-shell list. The `cheat` command prints
//! a concise cheat-sheet of the common flows, also derived from generic, org-agnostic examples.
//!
//! There is no `clap` in this CLI (the parser is hand-rolled), so completion is generated by hand
//! from the tree rather than by a derive macro — but it is still data-driven from a single table,
//! which is the property that prevents drift. A test (`completion_lists_every_top_level_subcommand`)
//! asserts the tree covers every dispatched subcommand, so a new verb that forgets to register here
//! fails CI rather than silently shipping without completion.

use crate::CliError;
use std::fmt::Write as _;
use std::io::Write;

/// One node of the command tree: a (sub)command name, its flags, and any nested subcommands.
pub(crate) struct Cmd {
    /// The literal subcommand token (e.g. `"pub"`, `"consumer-reset"`).
    pub name: &'static str,
    /// A one-line description, shown in zsh/fish completion and the cheat sheet.
    pub about: &'static str,
    /// The flags this command accepts (the literal `--xxx` strings, including aliases).
    pub flags: &'static [&'static str],
    /// Nested subcommands (e.g. `admin consumer-reset`), empty for a leaf command.
    pub subs: &'static [Cmd],
}

/// Flags accepted by EVERY command via the global pre-dispatch handling (`--json`) plus the
/// universal help flags. Offered on every command in completion.
pub(crate) const GLOBAL_FLAGS: &[&str] = &["--json", "--help", "-h"];

